// pnpm verify: prove every Aquahab memory exists on Walrus mainnet, independently of this server.
// Lists memories from the relayer, reads the owner's Blob objects from Sui through Tatum (with each Blob's
// on-chain namespace and author), matches them by blob id, and writes docs/PROOF.md.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { MemWal } from "@mysten-incubation/memwal";
import { CREW, suiscanObject, suiscanTx, walruscanBlob } from "../src/contract.ts";
import { env } from "../src/env.ts";
import { memwalAccount, ownedMemories } from "../src/chain/sui.ts";
import { tatumCallCount } from "../src/chain/tatum.ts";
import { configuredKeys } from "../src/views.ts";
import { blobIdToU256 } from "../src/util.ts";
import { SERVER_DIR } from "./envfile.ts";

const accountId = env.accountId();
// Any registered crew key can list the account's memories; prefer the Keeper's.
const keeper = env.roleKey("keeper") ?? env.roleKey("one");
if (!keeper) throw new Error("A crew delegate key (MEMWAL_KEY_KEEPER) is needed to list memories.");

const account = await memwalAccount(accountId);
const owner = account.owner;
const labels = new Map(account.delegateKeys.map((k) => [k.publicKeyHex, k.label]));
const keys = await configuredKeys();
for (const [role, pk] of Object.entries(keys)) if (pk && !labels.has(pk)) labels.set(pk, `${CREW[role as keyof typeof CREW].name} (not on payroll)`);

const mw = MemWal.create({ key: keeper, accountId, serverUrl: env.relayerUrl() });
const listed = [];
let cursor: string | undefined;
for (let i = 0; i < 50; i++) {
  const page = await mw.listMemories({ limit: 500, cursor });
  listed.push(...page.memories.filter((m) => m.namespace_id?.startsWith("aquahab:")));
  if (!page.has_more || !page.next_cursor) break;
  cursor = page.next_cursor;
}

const chain = await ownedMemories(owner);
const byU256 = new Map(chain.map((c) => [c.blobIdU256, c]));

const rows = listed
  .map((m) => {
    const c = byU256.get(blobIdToU256(m.blob_id));
    const nsOk = !!c && c.namespace === m.namespace_id;
    const author = c?.agentId ?? m.agent_id;
    return { m, c, ok: !!c && nsOk, author, label: author ? (labels.get(author) ?? "unknown key") : "unknown" };
  })
  .sort((a, b) => a.m.created_at.localeCompare(b.m.created_at));

const verified = rows.filter((r) => r.ok).length;
const byNs = new Map<string, { n: number; ok: number }>();
const byAuthor = new Map<string, { label: string; n: number }>();
for (const r of rows) {
  const e = byNs.get(r.m.namespace_id) ?? { n: 0, ok: 0 };
  e.n++;
  if (r.ok) e.ok++;
  byNs.set(r.m.namespace_id, e);
  if (r.author) {
    const a = byAuthor.get(r.author) ?? { label: r.label, n: 0 };
    a.n++;
    byAuthor.set(r.author, a);
  }
}
const days = new Set(rows.map((r) => r.m.created_at.slice(0, 10)));

const md = [
  "# PROOF",
  "",
  `Generated by \`pnpm verify\` on ${new Date().toISOString()}. Every row is a Walrus Memory listed by the mainnet relayer and matched, by blob id, to a Walrus \`Blob\` object owned by the Aquahab account owner on Sui, read through Tatum (GraphQL \`address.objects\` with the Blob's \`metadata\` dynamic field). The author column is the Blob's on-chain \`memwal_agent_id\`.`,
  "",
  `- MemWalAccount: [\`${accountId}\`](${suiscanObject(accountId)})`,
  `- Owner: [\`${owner}\`](${suiscanObject(owner)})`,
  `- Memories: **${rows.length}** across ${byNs.size} namespaces, on ${days.size} distinct days; **${verified}** verified on-chain`,
  `- Tatum calls for this report: ${tatumCallCount()}`,
  "",
  "## By room",
  "",
  "| Namespace | Memories | Verified on Sui |",
  "|---|---:|---:|",
  ...[...byNs.entries()].sort((a, b) => b[1].n - a[1].n).map(([ns, e]) => `| \`${ns}\` | ${e.n} | ${e.ok} |`),
  "",
  "## By employee (delegate key that signed the write)",
  "",
  "| Employee | Agent ID | Memories |",
  "|---|---|---:|",
  ...[...byAuthor.entries()].sort((a, b) => b[1].n - a[1].n).map(([pk, a]) => `| ${a.label} | \`${pk}\` | ${a.n} |`),
  "",
  "## Every memory",
  "",
  "| # | Stored | Namespace | Author | Blob | Sui object | Write tx | End epoch | Verified |",
  "|---:|---|---|---|---|---|---|---:|---|",
  ...rows.map(
    (r, i) =>
      `| ${i + 1} | ${r.m.created_at.slice(0, 16).replace("T", " ")} | \`${r.m.namespace_id}\` | ${r.label} | [\`${r.m.blob_id.slice(0, 10)}…\`](${walruscanBlob(r.m.blob_id)}) | ${r.c ? `[\`${r.c.objectId.slice(0, 10)}…\`](${suiscanObject(r.c.objectId)})` : "not found"} | ${r.c?.tx ? `[\`${r.c.tx.slice(0, 8)}…\`](${suiscanTx(r.c.tx)})` : ""} | ${r.c?.endEpoch ?? r.m.end_epoch ?? ""} | ${r.ok ? "yes" : "**no**"} |`,
  ),
  "",
].join("\n");

writeFileSync(path.join(SERVER_DIR, "..", "docs", "PROOF.md"), md);
console.log(`PROOF.md: ${rows.length} memories, ${verified} verified on-chain, ${byNs.size} rooms, ${days.size} days.`);
process.exit(verified === rows.length ? 0 : 1);
